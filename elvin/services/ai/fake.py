"""Deterministic stand-in models for automated tests and stress tests
(enabled with ELVIN_FAKE_AI=1). Never used in normal operation."""
from __future__ import annotations

import asyncio
import json
import os
import random
import re

from .providers import ChatResult, ImageInput, Provider, ProviderError

_CHANGE_WORDS = ("create", "add", "write", "build", "make", "fix", "implement", "change", "update", "refactor", "generate", "design", "rename", "delete")


def _last_user(messages: list[dict]) -> str:
    for m in reversed(messages):
        if m["role"] == "user":
            return m["content"] if isinstance(m["content"], str) else json.dumps(m["content"])
    return ""


def _task_text(messages: list[dict]) -> str:
    text = _last_user(messages)
    m = re.search(r"USER REQUEST:\s*(.+?)(?:\n[A-Z ]{4,}:|\Z)", text, re.S)
    return (m.group(1) if m else text).strip()


class FakeProvider(Provider):
    log: list[tuple[str, str]] = []  # (role, prompt text) - lets tests inspect what each model was sent

    def __init__(self, key: str, label: str, family: str, *, vision: bool = True) -> None:
        self.key, self.label, self.family = key, label, family
        self.model = f"fake-{key}"
        self.vision = vision
        self.context = 32000
        self.calls = 0

    async def _delay(self) -> None:
        self.calls += 1
        await asyncio.sleep(int(os.environ.get("ELVIN_FAKE_AI_DELAY_MS", "30")) / 1000)
        fail_rate = float(os.environ.get("ELVIN_FAKE_AI_FAIL_RATE", "0") or 0)
        fail_keys = os.environ.get("ELVIN_FAKE_AI_FAIL_KEYS", "")
        if (fail_keys and self.key in fail_keys.split(",")) or (fail_rate and random.random() < fail_rate):
            raise ProviderError(f"{self.label} injected failure", retryable=True, kind="network")

    async def chat(self, messages: list[dict], *, system: str | None = None, max_tokens: int = 2048,
                   json_mode: bool = False, images: list[ImageInput] | None = None, temperature: float = 0.2,
                   role: str = "", effort: str | None = None, model: str | None = None) -> ChatResult:
        await self._delay()
        FakeProvider.log.append((role, (system or "") + "\n" + "\n".join(str(m["content"]) for m in messages)))
        del FakeProvider.log[:-300]
        text = self._respond(role, messages, images)
        return ChatResult(text=text, provider=self.key, model=model or self.model,
                          usage={"prompt_tokens": sum(len(str(m["content"])) for m in messages) // 4, "completion_tokens": len(text) // 4})

    async def health(self) -> tuple[bool, str]:
        import os as _os
        down = _os.environ.get("ELVIN_FAKE_AI_DOWN_KEYS", "")
        return (self.key not in down.split(","), "online" if self.key not in down.split(",") else "unreachable (test)")

    async def fim(self, prefix: str, suffix: str, max_tokens: int = 96) -> str:
        await self._delay()
        last = prefix.rstrip().splitlines()[-1] if prefix.strip() else ""
        if last.rstrip().endswith(":"):
            return "    return None\n"
        return "  # suggested by fake Qwen\n"

    def _respond(self, role: str, messages: list[dict], images: list[ImageInput] | None) -> str:
        task = _task_text(messages)
        low = task.lower()
        if role == "planner":
            needs = any(w in low for w in _CHANGE_WORDS)
            libs = []
            for eco, name, ver in re.findall(r"use library (\w+):([\w.\-]+)@?([\w.\-]*)", task):
                libs.append({"ecosystem": eco, "name": name, "version": ver})
            steps = [{"title": "Write the code", "detail": task[:300]}] if needs else []
            if needs and "two steps" in low:
                steps.append({"title": "Add documentation", "detail": "Write a README"})
            return json.dumps({
                "reply": f"Plan ready for: {task[:80]}" if needs else f"Answer: {task[:200]}",
                "needs_changes": needs, "steps": steps, "files_to_read": [], "libraries": libs,
            })
        if role in ("coder", "fixer"):
            if re.search(r"CURRENT STEP \d+/\d+: Add documentation", _last_user(messages)):
                return "=== FILE: README.md ===\n# Project\n\nGenerated by the fake model.\n=== END FILE ===\n=== SUMMARY ===\nAdded a README.\n=== END SUMMARY ==="
            repair_round = "YOUR PREVIOUS ANSWER HAD PROBLEMS" in _last_user(messages)
            if "write broken python" in low:   # pastes test output into the file, like small models sometimes do
                if repair_round:
                    return "=== FILE: broken.py ===\nprint('fixed')\n=== END FILE ===\n=== SUMMARY ===\nRepaired.\n=== END SUMMARY ==="
                return ("=== FILE: broken.py ===\nprint('x'\n1 failed in 0.01s\n=== END FILE ===\n"
                        "=== SUMMARY ===\nOops.\n=== END SUMMARY ===")
            if "answer in markdown" in low:    # code in fences instead of FILE blocks
                if repair_round:
                    return "=== FILE: fenced.py ===\nprint('hi')\n=== END FILE ===\n=== SUMMARY ===\nResent.\n=== END SUMMARY ==="
                return "Here you go:\n```python\nprint('hi')\n```\n"
            dm = re.search(r"delete the file ([\w./-]+)", task)
            if dm:
                return f"=== DELETE: {dm.group(1)} ===\n=== SUMMARY ===\nDeleted {dm.group(1)}.\n=== END SUMMARY ==="
            m = re.search(r"file (?:called |named )?([\w./-]+\.\w+)", task)
            name = m.group(1) if m else "main.py"
            body = f"def hello():\n    return 'hello from elvin'\n\n\nif __name__ == '__main__':\n    print(hello())\n"
            out = f"=== FILE: {name} ===\n{body}=== END FILE ===\n"
            if "run it" in low or "and run" in low:
                out += f"=== RUN: python {name} ===\n"
            for eco, lib, ver in re.findall(r"use library (\w+):([\w.\-]+)@?([\w.\-]*)", task):
                out += f"=== LIBRARY: {eco} {lib} {ver} ===\n".replace("  ===", " ===")
            if "escape the folder" in low:
                out += "=== FILE: ../outside.txt ===\nnope\n=== END FILE ===\n"
            return out + "=== SUMMARY ===\nCreated the requested code.\n=== END SUMMARY ==="
        if role == "vision":
            return json.dumps({"title": "Landing page", "layout": "hero with headline and button", "colors": ["#0f172a", "#6366f1"],
                               "typography": "bold sans-serif", "sections": ["hero", "features"], "components": ["button"]})
        if role == "design":
            return ("=== FILE: index.html ===\n<!doctype html><html><head><link rel=\"stylesheet\" href=\"styles.css\"></head>"
                    "<body><h1>Hello</h1><button>Go</button></body></html>\n=== END FILE ===\n"
                    "=== FILE: styles.css ===\nbody{background:#0f172a;color:#fff;font-family:sans-serif}\n=== END FILE ===\n"
                    "=== SUMMARY ===\nBuilt the page.\n=== END SUMMARY ===")
        if role == "verify":
            return json.dumps({"score": 9, "matches": ["colors", "layout"], "differences": [], "fix_instructions": ""})
        if role == "ping":
            return "OK"
        if role == "summary":
            return "All done - the requested changes are in place."
        if role == "memory":
            facts = [s.strip() for s in re.split(r"[.!\n]", task) if re.search(r"\b(remember|always|prefer|never)\b", s, re.I)]
            return json.dumps({"facts": facts[:3]})
        if role == "bughunt":
            findings = []
            for mm in re.finditer(r"^FILE: (.+)$", _last_user(messages), re.M):
                pass
            current = ""
            for line in _last_user(messages).splitlines():
                fm = re.match(r"^FILE: (.+)$", line)
                if fm:
                    current = fm.group(1).strip()
                    continue
                lm = re.match(r"^\s*(\d+)\| (.*)$", line)
                if lm and ("eval(" in lm.group(2) or "os.system(" in lm.group(2)):
                    findings.append({"file": current, "line": int(lm.group(1)), "severity": "high", "category": "Code injection",
                                     "cwe": "CWE-95", "title": "Untrusted input reaches eval/os.system",
                                     "description": "User-controlled data is executed.", "recommendation": "Avoid eval; validate input."})
            return json.dumps({"findings": findings})
        if role == "terms":
            return json.dumps({"statements": [
                {"text": "The README asks you to credit the authors when you reuse this project.", "kind": "condition"},
                {"text": "The README says the project is provided for educational purposes.", "kind": "notice"},
            ], "summary": "Educational project; credit the authors."})
        if role == "simplify":
            items = re.findall(r'"id":\s*"([^"]+)"', _last_user(messages))
            return json.dumps({"items": [{"id": i, "plain": f"In plain words: rule {i}."} for i in items]})
        if role == "alternatives":
            return json.dumps({"alternatives": [{"name": "safe-alt", "reason": "Maintained and has no known vulnerabilities."}]})
        return "OK"
