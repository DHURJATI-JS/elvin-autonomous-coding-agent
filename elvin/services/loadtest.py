log = logging.getLogger("elvin.loadtest")
METHODS = {"GET", "POST", "PUT", "PATCH", "DELETE", "HEAD", "OPTIONS"}

LOCUSTFILE = '''# Generated by Elvin. Reads elvin_config.json; contains no user-provided code.
import json
import os

from locust import HttpUser, between

with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "elvin_config.json")) as fh:
    CONFIG = json.load(fh)


def _make_task(ep):
    method = ep["method"]
    path = ep["path"]
    name = ep.get("name") or f"{method} {path}"
    body = ep.get("json")
    headers = ep.get("headers") or {}

    def _task(user):
        kwargs = {"name": name, "headers": headers}
        if body is not None and method in ("POST", "PUT", "PATCH"):
            kwargs["json"] = body
        user.client.request(method, path, **kwargs)

    _task.__name__ = "task_" + str(abs(hash(name)))
    return _task


class ElvinUser(HttpUser):
    wait_time = between(CONFIG.get("wait_min", 0.5), CONFIG.get("wait_max", 2.0))
    tasks = {_make_task(ep): int(ep.get("weight", 1)) for ep in CONFIG["endpoints"]}
'''

_procs: dict[uuid.UUID, asyncio.subprocess.Process] = {}


def in_container() -> bool:
    return Path("/.dockerenv").exists() or os.environ.get("ELVIN_IN_DOCKER") == "1"


async def validate_target(raw: str) -> tuple[str, str]:
    """Return (normalized base URL, note). Raises ValueError if not allowed."""
    raw = (raw or "").strip()
    if "://" not in raw:
        raw = "http://" + raw
    parts = urlsplit(raw)
    if parts.scheme not in ("http", "https") or not parts.hostname:
        raise ValueError("Enter an http:// or https:// address, e.g. http://localhost:5000")
    if parts.username or parts.password:
        raise ValueError("Don't put credentials in the address.")
    host = parts.hostname
    note = ""
    if in_container() and host in ("localhost", "127.0.0.1", "::1", "0.0.0.0"):
        host = "host.docker.internal"
        note = "Elvin runs in Docker, so 'localhost' was mapped to your computer (host.docker.internal)."
    netloc = host if parts.port is None else f"{host}:{parts.port}"
    url = urlunsplit((parts.scheme, netloc, "", "", ""))
    if get_settings().loadtest_allow_public or host == "host.docker.internal":
        return url, note
    try:
        infos = await asyncio.get_running_loop().getaddrinfo(host, parts.port or (443 if parts.scheme == "https" else 80))
    except OSError as exc:
        raise ValueError(f"Can't resolve {host}.") from exc
    for info in infos:
        ip = ipaddress.ip_address(info[4][0])
        if not (ip.is_private or ip.is_loopback or ip.is_link_local):
            raise ValueError("For safety Elvin only load-tests apps on this computer or your local network. "
                             "(An administrator can allow public targets with LOADTEST_ALLOW_PUBLIC=true - only test "
                             "servers you own or are authorised to test.)")
    return url, note


def clean_endpoints(endpoints: list[dict[str, Any]]) -> list[dict[str, Any]]:
    out = []
    for ep in endpoints[: limits.LOADTEST_MAX_ENDPOINTS]:
        method = str(ep.get("method", "GET")).upper()
        path = str(ep.get("path", "/")).strip() or "/"
        if method not in METHODS:
            raise ValueError(f"Unsupported method {method}.")
        if not path.startswith("/") or "://" in path or len(path) > 500 or any(c in path for c in "\r\n"):
            raise ValueError(f"Path '{path[:60]}' must start with / and stay on the target host.")
        try:
            weight = int(ep.get("weight", 1))
        except (TypeError, ValueError):
            weight = 1
        weight = max(1, min(limits.LOADTEST_MAX_WEIGHT, weight))
        item: dict[str, Any] = {"method": method, "path": path, "weight": weight, "name": str(ep.get("name") or "")[:80]}
        body = ep.get("json")
        if isinstance(body, str) and body.strip():
            try:
                body = json.loads(body)
            except ValueError as exc:
                raise ValueError(f"The JSON body for {method} {path} is not valid JSON.") from exc
        if body not in (None, "") and len(json.dumps(body)) <= 20_000:
            item["json"] = body
        out.append(item)
    if not out:
        raise ValueError("Add at least one page/endpoint to test.")
    return out


def _f(value: str) -> float:
    try:
        return float(value)
    except (TypeError, ValueError):
        return 0.0


class _Tail:
    def __init__(self, path: Path) -> None:
        self.path = path
        self.offset = 0
        self.header: list[str] | None = None
        self.buffer = ""

    def read_rows(self) -> list[dict[str, str]]:
        if not self.path.exists():
            return []
        with open(self.path, encoding="utf-8", errors="replace") as fh:
            fh.seek(self.offset)
            chunk = fh.read()
            self.offset = fh.tell()
        self.buffer += chunk
        lines = self.buffer.split("\n")
        self.buffer = lines.pop()  # keep a partial line for next time
        rows = []
        for line in lines:
            if not line.strip():
                continue
            values = next(csv.reader([line]))
            if self.header is None:
                self.header = values
                continue
            rows.append(dict(zip(self.header, values)))
        return rows


async def run_loadtest(run_id: uuid.UUID, task_id: uuid.UUID, user_id: uuid.UUID, project_id: uuid.UUID, cfg: dict[str, Any]) -> None:
    workdir = Path(tempfile.mkdtemp(prefix="elvin-locust-"))
    prefix = workdir / "result"
    started = time.time()
    samples: list[dict[str, Any]] = []

    async def emit(type_: str, data: dict[str, Any], persist: bool = True) -> None:
        await tasks.emit(task_id, user_id, project_id, type_, {"run_id": str(run_id), **data}, persist=persist)

    try:
        await tasks.set_status(task_id, "running")
        (workdir / "elvin_config.json").write_text(json.dumps({"endpoints": cfg["endpoints"], "wait_min": 0.5, "wait_max": 2.0}))
        (workdir / "locustfile.py").write_text(LOCUSTFILE)
        cmd = [sys.executable, "-m", "locust", "-f", str(workdir / "locustfile.py"), "--headless",
               "-u", str(cfg["users"]), "-r", str(cfg["spawn_rate"]), "-t", f"{cfg['duration_s']}s",
               "--host", cfg["host"], "--csv", str(prefix), "--csv-full-history", "--stop-timeout", "5",
               "--only-summary", "--loglevel", "WARNING", "--exit-code-on-error", "0"]
        env = {"PATH": os.environ.get("PATH", "/usr/bin:/bin"), "HOME": str(workdir), "PYTHONUNBUFFERED": "1",
               "LANG": "C.UTF-8"}
        proc = await asyncio.create_subprocess_exec(*cmd, cwd=workdir, env=env, stdout=asyncio.subprocess.PIPE,
                                                    stderr=asyncio.subprocess.STDOUT, start_new_session=True)
        _procs[run_id] = proc
        await emit("loadtest_started", {"host": cfg["host"], "users": cfg["users"], "duration_s": cfg["duration_s"]})
        tail = _Tail(Path(f"{prefix}_stats_history.csv"))
        last_flush = time.time()
        pending: list[dict[str, Any]] = []
        deadline = started + cfg["duration_s"] + 60
        while True:
            try:
                await asyncio.wait_for(proc.wait(), timeout=2)
                finished = True
            except asyncio.TimeoutError:
                finished = False
            for row in await asyncio.to_thread(tail.read_rows):
                if row.get("Name") != "Aggregated":
                    continue
                t = round(_f(row.get("Timestamp")) - started, 1)
                sample = {"t": max(0.0, t), "users": int(_f(row.get("User Count"))), "rps": round(_f(row.get("Requests/s")), 2),
                          "fail_rps": round(_f(row.get("Failures/s")), 2), "p50": _f(row.get("50%")), "p95": _f(row.get("95%")),
                          "avg": round(_f(row.get("Total Average Response Time")), 1),
                          "total_requests": int(_f(row.get("Total Request Count"))),
                          "total_failures": int(_f(row.get("Total Failure Count")))}
                if len(samples) < limits.LOADTEST_MAX_SAMPLES:
                    samples.append(sample)
                    pending.append(sample)
                await emit("loadtest_sample", sample, persist=False)
            if pending and (finished or time.time() - last_flush > 5):
                async with dbm.session() as db:
                    db.add_all(LoadTestSample(run_id=run_id, **s) for s in pending)
                    await db.commit()
                pending, last_flush = [], time.time()
            if finished:
                break
            if time.time() > deadline:
                await stop_process(run_id)
        output = (await proc.stdout.read()).decode(errors="replace")[-4000:] if proc.stdout else ""
        stats = await asyncio.to_thread(_read_stats, Path(f"{prefix}_stats.csv"))
        failures = await asyncio.to_thread(_read_failures, Path(f"{prefix}_failures.csv"))
        agg = next((s for s in stats if s["name"] == "Aggregated"), None)
        reason = tasks.manager.reason(task_id)
        status = "stopped" if reason else ("completed" if agg else "failed")
        async with dbm.session() as db:
            db.add_all(LoadTestEndpointStat(run_id=run_id, **{k: v for k, v in s.items()}) for s in stats if s["name"] != "Aggregated")
            values: dict[str, Any] = {"status": status, "finished_at": utcnow(),
                                      "summary": {"failures": failures[:30], "log_tail": output[-1500:], "samples": len(samples)}}
            if agg:
                values.update(total_requests=agg["requests"], total_failures=agg["failures"], avg_ms=agg["avg"], p50_ms=agg["median"],
                              p95_ms=agg["p95"], p99_ms=agg["p99"], max_ms=agg["max"], rps=agg["rps"])
            else:
                values["error"] = "Locust produced no results. Is the target app running and reachable?\n" + output[-800:]
            await db.execute(update(LoadTestRun).where(LoadTestRun.id == run_id).values(**values))
            await db.commit()
        await _prune(project_id)
        await tasks.set_status(task_id, "completed" if status != "failed" else "failed", error=values.get("error"))
        await emit("loadtest_done", {"status": status})
        if cfg.get("origin") == "elvin":
            await _report_to_chat(run_id, user_id, project_id, status, agg, values.get("error"))
    except asyncio.CancelledError:
        await stop_process(run_id)
        async with dbm.session() as db:
            await db.execute(update(LoadTestRun).where(LoadTestRun.id == run_id).values(status="stopped", finished_at=utcnow()))
            await db.commit()
        await tasks.set_status(task_id, "cancelled", error="Stopped.")
        await emit("loadtest_done", {"status": "stopped"})
        raise
    except Exception as exc:
        log.warning("load test failed: %s", exc)
        async with dbm.session() as db:
            await db.execute(update(LoadTestRun).where(LoadTestRun.id == run_id).values(status="failed", finished_at=utcnow(), error=str(exc)[:500]))
            await db.commit()
        await tasks.set_status(task_id, "failed", error=str(exc)[:500])
        await emit("loadtest_done", {"status": "failed", "error": str(exc)[:500]})
    finally:
        _procs.pop(run_id, None)
        shutil.rmtree(workdir, ignore_errors=True)


async def stop_process(run_id: uuid.UUID) -> None:
    proc = _procs.get(run_id)
    if proc is None or proc.returncode is not None:
        return
    with contextlib.suppress(ProcessLookupError, PermissionError):
        os.killpg(proc.pid, signal.SIGTERM)  # locust writes its final CSVs on SIGTERM
    try:
        await asyncio.wait_for(proc.wait(), timeout=15)
    except asyncio.TimeoutError:
        with contextlib.suppress(ProcessLookupError, PermissionError):
            os.killpg(proc.pid, signal.SIGKILL)


def _read_stats(path: Path) -> list[dict[str, Any]]:
    if not path.exists():
        return []
    out = []
    with open(path, encoding="utf-8", errors="replace") as fh:
        for row in csv.DictReader(fh):
            out.append({"method": (row.get("Type") or "")[:10], "name": (row.get("Name") or "")[:300],
                        "requests": int(_f(row.get("Request Count"))), "failures": int(_f(row.get("Failure Count"))),
                        "median": _f(row.get("Median Response Time")), "avg": round(_f(row.get("Average Response Time")), 1),
                        "min": _f(row.get("Min Response Time")), "max": _f(row.get("Max Response Time")),
                        "p90": _f(row.get("90%")), "p95": _f(row.get("95%")), "p99": _f(row.get("99%")),
                        "rps": round(_f(row.get("Requests/s")), 2), "fail_rps": round(_f(row.get("Failures/s")), 2),
                        "avg_size": round(_f(row.get("Average Content Size")), 1)})
    return out


def _read_failures(path: Path) -> list[dict[str, Any]]:
    if not path.exists():
        return []
    with open(path, encoding="utf-8", errors="replace") as fh:
        return [{"method": r.get("Method", ""), "name": r.get("Name", ""), "error": (r.get("Error") or "")[:300],
                 "occurrences": int(_f(r.get("Occurrences")))} for r in csv.DictReader(fh)][:50]


async def _prune(project_id: uuid.UUID) -> None:
    async with dbm.session() as db:
        count = (await db.execute(select(func.count()).select_from(LoadTestRun).where(LoadTestRun.project_id == project_id))).scalar_one()
        if count > limits.LOADTEST_RUNS_KEPT:
            old = (await db.execute(select(LoadTestRun.id).where(LoadTestRun.project_id == project_id)
                                    .order_by(LoadTestRun.started_at.asc()).limit(count - limits.LOADTEST_RUNS_KEPT))).scalars().all()
            await db.execute(delete(LoadTestRun).where(LoadTestRun.id.in_(old)))
            await db.commit()


def _cell(value: Any) -> Any:
    """Neutralise spreadsheet formula injection."""
    if isinstance(value, str) and value[:1] in ("=", "+", "-", "@", "\t", "\r"):
        return "'" + value
    return value


def to_csv(run: LoadTestRun, stats: list[LoadTestEndpointStat], samples: list[LoadTestSample]) -> str:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["Elvin load test", str(run.id)])
    w.writerow(["Target", _cell(run.config.get("host", "")), "Users", run.config.get("users"), "Spawn rate",
                run.config.get("spawn_rate"), "Duration (s)", run.config.get("duration_s")])
    w.writerow(["Started", run.started_at.isoformat(), "Finished", run.finished_at.isoformat() if run.finished_at else "", "Status", run.status])
    w.writerow([])
    w.writerow(["Summary", "Requests", "Failures", "Avg ms", "p50 ms", "p95 ms", "p99 ms", "Max ms", "Req/s"])
    w.writerow(["Aggregated", run.total_requests, run.total_failures, run.avg_ms, run.p50_ms, run.p95_ms, run.p99_ms, run.max_ms, run.rps])
    w.writerow([])
    w.writerow(["Method", "Endpoint", "Requests", "Failures", "Median ms", "Avg ms", "Min ms", "Max ms", "p90 ms", "p95 ms", "p99 ms",
                "Req/s", "Failures/s", "Avg size (bytes)"])
    for s in stats:
        w.writerow([_cell(s.method), _cell(s.name), s.requests, s.failures, s.median, s.avg, s.min, s.max, s.p90, s.p95, s.p99,
                    s.rps, s.fail_rps, s.avg_size])
    w.writerow([])
    w.writerow(["Seconds", "Users", "Req/s", "Failures/s", "p50 ms", "p95 ms", "Avg ms", "Total requests", "Total failures"])
    for s in samples:
        w.writerow([s.t, s.users, s.rps, s.fail_rps, s.p50, s.p95, s.avg, s.total_requests, s.total_failures])
    return buf.getvalue()


async def _report_to_chat(run_id: uuid.UUID, user_id: uuid.UUID, project_id: uuid.UUID, status: str,
                          agg: dict[str, Any] | None, error: str | None) -> None:
    if agg:
        fail_pct = 100 * agg["failures"] / agg["requests"] if agg["requests"] else 0
        text = (f"**Stress test {status}.** {agg['requests']:,} requests, {agg['failures']:,} failures ({fail_pct:.1f}%), "
                f"average {agg['avg']:.0f} ms, p95 {agg['p95']:.0f} ms, p99 {agg['p99']:.0f} ms, {agg['rps']:.1f} requests/s. "
                f"Charts and the CSV export are on the Load Test page.")
    else:
        text = f"**Stress test {status}.** {error or 'Locust produced no results.'}"
    async with dbm.session() as db:
        db.add(Message(project_id=project_id, user_id=user_id, role="elvin", content=text,
                       meta={"kind": "loadtest_report", "run_id": str(run_id)}))
        await db.commit()
    tasks.notify(user_id, "chat_message", {"project_id": str(project_id), "role": "elvin", "content": text,
                                          "meta": {"kind": "loadtest_report", "run_id": str(run_id)}})


class LoadTestRejected(ValueError):
    pass


async def launch(db, user: User, project: Project, raw: dict[str, Any], *, origin: str = "page") -> tuple[LoadTestRun, Task]:
    """Validate a load-test request and start it in the background."""
    host, note = await validate_target(str(raw.get("host", "")))
    endpoints = clean_endpoints(list(raw.get("endpoints") or []))

    def clamp(value: Any, lo: int, hi: int, default: int) -> int:
        try:
            return max(lo, min(hi, int(value)))
        except (TypeError, ValueError):
            return default

    cfg = {"host": host, "endpoints": endpoints, "origin": origin, "note": note,
           "users": clamp(raw.get("users"), 1, limits.LOADTEST_MAX_USERS, 10),
           "spawn_rate": clamp(raw.get("spawn_rate"), 1, limits.LOADTEST_MAX_SPAWN_RATE, 2),
           "duration_s": clamp(raw.get("duration_s"), limits.LOADTEST_MIN_DURATION_S, limits.LOADTEST_MAX_DURATION_S, 60)}
    await db.execute(select(Project.id).where(Project.id == project.id).with_for_update())
    busy = (await db.execute(select(LoadTestRun.id).where(LoadTestRun.project_id == project.id,
                                                          LoadTestRun.status == "running"))).first()
    if busy:
        await db.commit()
        raise LoadTestRejected("A load test is already running for this project - stop it or wait for it to finish.")
    task = Task(user_id=user.id, project_id=project.id, kind="loadtest", status="queued",
                title=f"Load test {host} ({cfg['users']} users, {cfg['duration_s']}s)"[:200], params=cfg)
    db.add(task)
    await db.flush()
    run = LoadTestRun(project_id=project.id, user_id=user.id, task_id=task.id, config=cfg, status="running")
    db.add(run)
    await db.commit()
    tasks.manager.launch(task, run_loadtest(run.id, task.id, user.id, project.id, cfg))
    return run, task
