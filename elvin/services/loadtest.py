"""Locust stress testing of the user's own app.

The locustfile is a fixed template that reads a JSON config (paths, methods,
weights, bodies) - nothing the user types is ever pasted into Python code.
Locust runs headless in a subprocess for the chosen duration; Elvin tails its
CSV history to stream live charts, then stores the run, per-endpoint stats and
the time series in PostgreSQL. Targets are limited to this computer and the
local network unless LOADTEST_ALLOW_PUBLIC=true (load-testing other people's
servers without permission is illegal in most places)."""
